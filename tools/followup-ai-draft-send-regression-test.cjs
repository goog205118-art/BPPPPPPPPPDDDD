function readRequestBody(req) {
  return new Promise((resolve, reject) => {
    let raw = "";
    req.on("data", (chunk) => {
      raw += chunk;
    });
    req.on("end", () => resolve(raw));
    req.on("error", reject);
  });
}

function startFakeAiServer() {
  return new Promise((resolve, reject) => {
    fakeAiServer = http.createServer(async (req, res) => {
      try {
        const payload = JSON.parse((await readRequestBody(req)) || "{}");
        const prompt = String(payload.messages?.find((message) => message?.role === "user")?.content || "");
        fakeAiRequests.push({ pathname: req.url, prompt });
        const draft = {
          subject: "Follow-up collaboration details",
          body: "Hello,\n\nWe would love to continue the collaboration discussion.\n\nBest Regards\nGenerated by model",
          warnings: [],
        };
        res.writeHead(200, { "Content-Type": "application/json" });
        res.end(JSON.stringify({ choices: [{ message: { content: JSON.stringify(draft) } }] }));
      } catch (error) {
        res.writeHead(500, { "Content-Type": "application/json" });
        res.end(JSON.stringify({ error: { message: error.message } }));
      }
    });
    fakeAiServer.once("error", reject);
    fakeAiServer.listen(0, "127.0.0.1", () => {
      const address = fakeAiServer.address();
      fakeAiBaseUrl = `http://127.0.0.1:${address.port}/v1`;
      resolve();
    });
  });
}

function waitForServer(timeoutMs = 15000) {
  const deadline = Date.now() + timeoutMs;
  return new Promise((resolve, reject) => {
    const check = async () => {
      try {
        if ((await fetch(`${baseUrl}/api/state`)).ok) return resolve();
      } catch {
        // The isolated SQLite database is initialized during startup.
      }
      if (Date.now() >= deadline) return reject(new Error("AI 草稿与发送确认测试服务启动超时。"));
      setTimeout(check, 150);
    };
    void check();
  });
}

async function request(pathname, options = {}) {
  const response = await fetch(`${baseUrl}${pathname}`, options);
  const payload = await response.json().catch(() => ({}));
  return { response, payload };
}

function jsonOptions(method, payload) {
  return {
    method,
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload),
  };
}

function assertEmailFormatting() {
  const signatureHtml = [
    '<div style="font-family:Arial,sans-serif"><strong>品牌 A 团队</strong></div>',
    '<div><a href="https://brand-a.example/">品牌官网</a></div>',
    '<img src="data:image/png;base64,iVBORw0KGgo=" alt="Brand A">',
  ].join("");
  const formatted = formatEmailContent(
    [
      "Hello creator,",
      "",
      "Here are all selected products:",
      "https://example.com/products/one",
      "https://example.com/products/two",
      "https://example.com/products/three",
      "",
      "Best Regards",
      "Generated by model",
    ].join("\n"),
    "",
    { signatureHtml },
  );
  for (const url of [
    "https://example.com/products/one",
    "https://example.com/products/two",
    "https://example.com/products/three",
  ]) {
    assert.match(formatted.text, new RegExp(url.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")), `正文不能丢失产品链接：${url}`);
    assert.match(formatted.html, new RegExp(`href="${url.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}"`), `HTML 不能丢失产品链接：${url}`);
  }
  assert.match(formatted.text, /品牌 A 团队/);
  assert.doesNotMatch(formatted.text, /Generated by model/);
  assert.equal((formatted.html.match(/品牌 A 团队/g) || []).length, 1, "正式签名只能追加一次。");
  assert.equal(formatted.attachments.length, 1, "HTML 签名的 base64 图片必须转为 CID 附件。");
  assert.match(formatted.html, /cid:signature-[a-f0-9]+@resource-workbench/);
  assert.deepEqual(
    signatureAuditDetails({ signatureHtml }, formatted),
    { signature_applied: true, signature_mode: "html", signature_has_image: true },
  );
}

function assertFrontendContract() {
  const appSource = fs.readFileSync(path.join(rootDir, "app", "app.js"), "utf8");
  const localServerSource = fs.readFileSync(path.join(rootDir, "tools", "local-server.cjs"), "utf8");
  const vercelRouteSource = fs.readFileSync(path.join(rootDir, "api", "[...route].mjs"), "utf8");
  assert.match(appSource, /data-followup-send-confirmed/, "跟进详情必须展示人工发送确认勾选。");
  assert.match(appSource, /data-followup-signature-status/, "跟进详情必须展示当前官方邮箱签名状态。");
  assert.match(
    appSource,
    /followUpId: followUp\.id,[\s\S]*?confirmed: true,/,
    "跟进回复的发送请求必须携带已确认标记。",
  );
  assert.match(
    appSource,
    /leadId: lead\.id,[\s\S]*?confirmed: true,/,
    "待开发达人首联的发送请求必须携带已确认标记。",
  );
  for (const [name, source] of [["本地服务", localServerSource], ["Vercel 路由", vercelRouteSource]]) {
    assert.match(
      source,
      /\.map\(\(productId\) => followUpText\(productId\)\)/,
      `${name} 必须避免把 Array.map 的索引误作为文本最大长度，导致产品 ID 截断。`,
    );
    assert.doesNotMatch(source, /\.map\(followUpText\)/, `${name} 不得直接把带长度参数的文本函数传给 Array.map。`);
  }
}

